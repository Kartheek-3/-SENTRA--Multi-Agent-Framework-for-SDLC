import os
import shutil
import json
from backend.models.state import ProjectState
from backend.agents.analysis_agent import AnalysisAgent
from backend.agents.planning_agent import PlanningAgent
from backend.agents.coding_agent import CodingAgent
from backend.agents.qa_agent import QAAgent
from backend.agents.delivery_agent import DeliveryAgent
from backend.llm.model_router import ModelRouter
from backend.utils import slugify

def main():
    print("====================================")
    print("SEAM END-TO-END EXECUTION PROTOTYPE")
    print("====================================")
    
    project_id = "E-Commerce E2E"
    user_requirement = "Build an e-commerce backend API with users and products."
    
    proj_dir = os.path.join("generated_projects", slugify(project_id))
    if os.path.exists(proj_dir):
        shutil.rmtree(proj_dir)
        
    state = ProjectState(project_id=project_id, user_requirement=user_requirement)
    router = ModelRouter()
    
    # 1. Analysis
    print("\n--- Running AnalysisAgent ---")
    analysis_agent = AnalysisAgent(router)
    state = analysis_agent.process(state)
    if state.errors:
        print("Analysis Failed!")
        return
        
    # 2. Planning
    print("\n--- Running PlanningAgent ---")
    planning_agent = PlanningAgent(router)
    state = planning_agent.process(state)
    if state.errors:
        print("Planning Failed!")
        for e in state.errors:
            print(e)
        return
        
    # Extract tasks
    tasks_to_run = state.project_plan.tasks
    if not tasks_to_run:
        print("No tasks generated by PlanningAgent!")
        return
        
    print("\n--- Verifying Persistent Artifacts ---")
    expected_files = [
        "analysis/requirements_analysis.md",
        "design/system_design.md",
        "design/architecture.md",
        "design/diagrams/architecture.json",
        "design/diagrams/use_case.json",
        "design/diagrams/class.json",
        "design/diagrams/object.json",
        "design/diagrams/sequence.json",
        "design/diagrams/activity.json",
        "design/diagrams/dfd_level_0.json",
        "design/diagrams/dfd_level_1.json",
    ]
    for f in expected_files:
        f_path = os.path.join(proj_dir, f)
        if not os.path.exists(f_path):
            print(f"MISSING ARTIFACT: {f_path}")
            return
    print("All structured outputs properly persisted!")
    
    coding_agent = CodingAgent(router)
    qa_agent = QAAgent(router)
    
    # 3. Coding and QA Loop
    print("\n--- Running Coding & QA ---")
    for task in tasks_to_run:
        print(f"\nProcessing Task: {task.task_id} - {task.title}")
        
        # Coding
        state = coding_agent.process(state, task.task_id)
        if task.status != "completed":
            print(f"Task {task.task_id} failed coding!")
            for e in state.errors:
                print(e)
            return
            
        print(f"Code Generation: SUCCESS")
        
        # QA
        state = qa_agent.process(state, task.task_id)
        
        qa_report_path = os.path.join(proj_dir, "qa", f"{task.task_id}_qa_report.md")
        if not os.path.exists(qa_report_path):
            print(f"MISSING QA REPORT: {qa_report_path}")
            return
            
        if task.status != "completed":
            print(f"Task {task.task_id} failed QA!")
            qa_res = task.result.get("qa_result", {})
            print(json.dumps(qa_res, indent=2))
            return
            
        print(f"QA Validation: SUCCESS")
        
    # 4. Delivery
    print("\n--- Running DeliveryAgent ---")
    delivery_agent = DeliveryAgent()
    state = delivery_agent.process(state)
    
    res = getattr(state, "delivery_result", None)
    if not res or res.get("status") != "deployed":
        print("Delivery Failed!")
        print(res.get("errors") if res else "No result")
        return
        
    print("\n====================================")
    print("END-TO-END EXECUTION COMPLETE!")
    print("====================================")
    print(f"Project Name: {res['project_name']}")
    print(f"Status: {res['status']}")
    print(f"QA Verified: {res['qa_verified']}")
    print(f"Docs Generated: {res['documentation_generated']}")
    print(f"Package Created: {res['package_created']}")
    print(f"Artifact Paths: {res['artifact_paths']}")

if __name__ == "__main__":
    main()
